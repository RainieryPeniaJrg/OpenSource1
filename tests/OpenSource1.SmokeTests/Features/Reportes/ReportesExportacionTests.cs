public sealed class ReportesExportacionValidacionTests
{
    [Fact]
    public async Task FiltrosInvalidos_NoAbrenTransaccion()
    {
        var sesion = new Mock<IDbSession>(MockBehavior.Strict);
        sesion.SetupGet(s => s.HayTransaccionActiva).Returns(false);
        var servicio = new ReportesExportacionService(sesion.Object, Mock.Of<IReportesReadRepository>());
        var resultado = await servicio.VentasAsync(new(Estado: "invalido"), default);
        Assert.True(resultado.EsFallo);
        Assert.Contains(resultado.Errores, e => e.Campo == "Estado");
        sesion.Verify(s => s.BeginTransactionAsync(It.IsAny<CancellationToken>()), Times.Never);
    }

    [Fact]
    public async Task TransaccionAjena_NoReutilizaUnaInstantaneaNoGarantizada()
    {
        var sesion = new Mock<IDbSession>(MockBehavior.Strict);
        sesion.SetupGet(s => s.HayTransaccionActiva).Returns(true);
        var servicio = new ReportesExportacionService(sesion.Object, Mock.Of<IReportesReadRepository>());
        await Assert.ThrowsAsync<InvalidOperationException>(() => servicio.VentasAsync(new(), default));
        sesion.Verify(s => s.BeginTransactionAsync(It.IsAny<CancellationToken>()), Times.Never);
    }
}

[Collection(PostgresCollection.Name)]
public sealed class ReportesExportacionPostgresTests(PostgresTestFixture fixture) : IClassFixture<PostgresTestFixture>
{
    static ReportesExportacionPostgresTests() => SqlMapper.AddTypeHandler(new DapperDateOnlyTypeHandler());

    [Fact]
    public async Task RespuestaIncompleta_NoEntregaUnArchivoParcialYLiberaTransaccion()
    {
        var config = new ConfigurationBuilder().AddInMemoryCollection(new Dictionary<string, string?>
            { ["ConnectionStrings:DefaultConnection"] = fixture.AppConnectionString }).Build();
        await using var sesion = new DbSession(config);
        var repository = new Mock<IReportesReadRepository>();
        repository.Setup(r => r.VentasAsync(It.IsAny<ReporteCriterios>(), It.IsAny<CancellationToken>()))
            .ReturnsAsync(new ReporteResponse<VentaReporteFila>(new([new() { Numero = "FV001" }], 1, 200, 2), new(), new(2026, 1, 31)));

        var servicio = new ReportesExportacionService(sesion, repository.Object);
        var resultado = await servicio.VentasAsync(new(Hasta: new(2026, 1, 31)), default);

        Assert.True(resultado.EsFallo);
        Assert.Equal("reporte.exportacion_incompleta.conflicto", Assert.Single(resultado.Errores).Codigo);
        Assert.False(sesion.HayTransaccionActiva);
    }

    [Fact]
    public async Task Exportacion_ConFacturaConcurrenteEntrePaginas_ConservaSnapshotSinDuplicarNiOmitir()
    {
        var esquema = $"exportacion_{Guid.NewGuid():N}";
        await using var externo = new NpgsqlConnection(fixture.AppConnectionString);
        await externo.OpenAsync();
        // The schema name is generated by this test, never accepted from user input.
        await externo.ExecuteAsync($"CREATE SCHEMA {esquema}");
        try
        {
            await externo.ExecuteAsync($"SET search_path TO {esquema}");
            await externo.ExecuteAsync("""
                CREATE TABLE "FacturasVenta" ("Numero" text, "FechaRegistro" date, "SocioNegocioFacturarAId" uuid,
                    "NombreFacturacion" text, "Moneda" text, "ImporteTotal" numeric);
                CREATE TABLE "NotasCreditoVenta" (LIKE "FacturasVenta");
                CREATE TABLE "LineasFacturaVenta" ("FacturaVentaNumero" text, "ProductoId" uuid, "AlmacenId" uuid);
                CREATE TABLE "LineasNotaCreditoVenta" ("NotaCreditoVentaNumero" text, "ProductoId" uuid, "AlmacenId" uuid);
                INSERT INTO "FacturasVenta" SELECT 'FV' || lpad(i::text, 3, '0'), '2026-01-01',
                    '11111111-1111-1111-1111-111111111111', 'Cliente', 'DOP', 1 FROM generate_series(1, 201) i;
                """);
            var cadena = new NpgsqlConnectionStringBuilder(fixture.AppConnectionString) { SearchPath = esquema }.ConnectionString;
            var config = new ConfigurationBuilder().AddInMemoryCollection(new Dictionary<string, string?>
                { ["ConnectionStrings:DefaultConnection"] = cadena }).Build();
            await using var sesion = new DbSession(config);
            var real = new DapperReportesReadRepository(sesion, Mock.Of<IMovimientoClienteReadRepository>());
            var repository = new Mock<IReportesReadRepository>();
            var paginas = new List<int>();
            repository.Setup(r => r.VentasAsync(It.IsAny<ReporteCriterios>(), It.IsAny<CancellationToken>()))
                .Returns(async (ReporteCriterios c, CancellationToken ct) =>
                {
                    paginas.Add(c.Pagina);
                    Assert.Equal("repeatable read", await sesion.Connection.ExecuteScalarAsync<string>(
                        "SHOW transaction_isolation", transaction: sesion.CurrentTransaction));
                    Assert.Equal("on", await sesion.Connection.ExecuteScalarAsync<string>(
                        "SHOW transaction_read_only", transaction: sesion.CurrentTransaction));
                    var respuesta = await real.VentasAsync(c, ct);
                    if (c.Pagina == 1)
                        await externo.ExecuteAsync("""INSERT INTO "FacturasVenta" VALUES ('FV000','2026-01-01','11111111-1111-1111-1111-111111111111','Concurrente','DOP',1000)""");
                    return respuesta;
                });

            var servicio = new ReportesExportacionService(sesion, repository.Object);
            var resultado = await servicio.VentasAsync(new(Hasta: new(2026, 1, 31), Pagina: 2), default);

            Assert.True(resultado.EsExito, string.Join(';', resultado.Errores));
            Assert.Equal(new[] { 1, 2 }, paginas);
            Assert.Equal(201, resultado.Valor.Pagina.Items.Count);
            Assert.Equal(201, resultado.Valor.Pagina.Total);
            Assert.Equal(201m, resultado.Valor.Totales.Ventas);
            Assert.Equal(201, resultado.Valor.Pagina.Items.Select(x => x.Numero).Distinct().Count());
            Assert.Equal("FV001", resultado.Valor.Pagina.Items[0].Numero);
            Assert.Equal("FV201", resultado.Valor.Pagina.Items[^1].Numero);
            Assert.DoesNotContain(resultado.Valor.Pagina.Items, x => x.Numero == "FV000");
            Assert.False(sesion.HayTransaccionActiva);
            // Original: Assert.Equal(202L, await externo.ExecuteScalarAsync<long>("""SELECT COUNT(*) FROM "FacturasVenta""""));
            Assert.Equal(202L, await externo.ExecuteScalarAsync<long>("SELECT COUNT(*) FROM \"FacturasVenta\""));
        }
        finally
        {
            await externo.ExecuteAsync($"DROP SCHEMA {esquema} CASCADE");
        }
    }
}
